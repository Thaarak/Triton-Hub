create table if not exists public.profiles (
  id uuid primary key references auth.users on delete cascade,
  full_name text,
  email text unique not null,
  updated_at timestamptz default now()
);

alter table public.profiles enable row level security;
drop policy if exists "Users can view their own profile." on public.profiles;
drop policy if exists "Users can update own profile." on public.profiles;
create policy "Users can view their own profile." on public.profiles
  for select to authenticated using ((select auth.uid()) = id);
create policy "Users can update own profile." on public.profiles
  for update to authenticated using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email, new.raw_user_meta_data ->> 'full_name')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

insert into public.profiles (id, email, full_name)
select id, email, raw_user_meta_data ->> 'full_name' from auth.users where email is not null
on conflict (id) do nothing;

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users on delete cascade,
  created_at timestamptz not null default now(),
  source text not null,
  category text not null,
  summary text not null,
  snippet text,
  event_date text not null default 'EMPTY',
  event_time text not null default 'EMPTY',
  urgency text not null default 'medium',
  link text not null default 'EMPTY',
  completed boolean not null default false
);

alter table public.notifications add column if not exists completed boolean not null default false;
alter table public.notifications add column if not exists snippet text;
create index if not exists notifications_user_created_idx on public.notifications (user_id, created_at desc);
alter table public.notifications enable row level security;

-- Older deployments may have manually configured policies. Rebuild them before
-- relying on ownership checks in a database with existing student records.
do $$
declare old_policy record;
begin
  for old_policy in select tablename, policyname from pg_policies
    where schemaname = 'public' and tablename in ('notifications', 'profiles')
    and policyname not in ('Users can view their own profile.', 'Users can update own profile.')
  loop
    execute format('drop policy %I on public.%I', old_policy.policyname, old_policy.tablename);
  end loop;
end $$;

create policy notifications_read_own on public.notifications
  for select to authenticated using ((select auth.uid()) = user_id);
create policy notifications_insert_own on public.notifications
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy notifications_update_own on public.notifications
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

revoke all on public.profiles, public.notifications from anon, authenticated;
grant select, update on public.profiles to authenticated;
grant select, insert, update on public.notifications to authenticated;
grant all on public.profiles, public.notifications to service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;
